#!/bin/bash
set -e

# ==============================================================================
# Firmware Build & Packaging Script
# ==============================================================================
#
# Partition layout (4 MB Flash):
#   - 0x0000  - 0x8000  : Bootloader (32 KiB)
#   - 0x8000  - 0x9000  : Partition Table (4 KiB)
#   - 0x9000  - 0xD000  : NVS (16 KiB) [PRESERVED - contains device state]
#   - 0xF000  - 0x10000 : PHY init (4 KiB)
#   - 0x10000 - 0x400000: Factory App (4032 KiB)
#
# ==============================================================================
# FLASHING INSTRUCTIONS:
#
# 1. UPDATING EXISTING UNITS IN THE FIELD (PRESERVING NVS DATA):
#    CRITICAL: Never run chip erase (`erase_flash` or `espflash ... --erase-parts`)
#    because that will wipe existing user data in the NVS partition (0x9000-0xD000).
#
#    Using espflash:
#      espflash write-bin 0x8000 /tmp/partitions.bin
#      espflash write-bin 0x10000 /tmp/app.bin
#
#    Using esptool.py:
#      esptool.py --chip esp32s3 write_flash 0x8000 /tmp/partitions.bin 0x10000 /tmp/app.bin
#
# 2. PROVISIONING BRAND NEW / BLANK UNITS:
#    The merged binary contains bootloader, partition table, and the factory app.
#
#    Using espflash:
#      espflash write-bin 0x0 /tmp/image.bin
#
#    Using esptool.py:
#      esptool.py --chip esp32s3 write_flash 0x0 /tmp/image.bin
# ==============================================================================

SIGNED=false

for arg in "$@"; do
    case "$arg" in
        --signed)
            SIGNED=true
            ;;
        -h|--help)
            echo "Usage: $(basename "$0") [--signed]"
            echo ""
            echo "Options:"
            echo "  --signed    Sign application binary and export signed bootloader for Secure Boot v2"
            echo "  -h, --help  Show this help message"
            exit 0
            ;;
        *)
            echo "Unknown argument: $arg"
            echo "Usage: $(basename "$0") [--signed]"
            exit 1
            ;;
    esac
done

if [ "$SIGNED" = true ]; then
    echo "Mode: SIGNED (Secure Boot v2)"
else
    echo "Mode: UNSIGNED (Default)"
fi

echo "Building release binary..."
cargo build --release

echo "Packaging merged 4MB image..."
# Make a merged binary that contains the bootloader, partition table, and app
espflash save-image --chip esp32s3 target/xtensa-esp32s3-espidf/release/tartarus-firmware /tmp/image.bin --flash-size=4mb --merge

# Extract individual binaries for selective flashing
dd if=/tmp/image.bin of=/tmp/partitions.bin bs=1K skip=32 count=4
dd if=/tmp/image.bin of=/tmp/bootloader_4mb.bin bs=1K count=32

echo "Packaging standalone factory app binary..."
# Make the standalone main app (target offset 0x10000)
espflash save-image --chip esp32s3 target/xtensa-esp32s3-espidf/release/tartarus-firmware /tmp/app.bin --flash-size=4mb

if [ "$SIGNED" = true ]; then
    # Copy signed bootloader generated by the esp-idf-sys build
    BOOTLOADER_SRC=$(find target/xtensa-esp32s3-espidf/release/build -name "bootloader.bin" 2>/dev/null | head -n 1)
    if [ -n "$BOOTLOADER_SRC" ] && [ -f "$BOOTLOADER_SRC" ]; then
        echo "Copying signed bootloader from ${BOOTLOADER_SRC}..."
        cp "$BOOTLOADER_SRC" /tmp/bootloader.bin
    else
        echo "Warning: Signed bootloader not found in target build directory."
        cp /tmp/bootloader_4mb.bin /tmp/bootloader.bin
    fi

    KEY_FILE="secure_boot_signing_key.pem"
    ESP_SECURE_PY=$(which espsecure.py 2>/dev/null || find .embuild/espressif/python_env -name espsecure.py 2>/dev/null | head -n 1)

    if [ -f "$KEY_FILE" ] && [ -n "$ESP_SECURE_PY" ]; then
        echo "Signing standalone app with Secure Boot v2 key..."
        "$ESP_SECURE_PY" sign_data --version 2 --keyfile "$KEY_FILE" --output /tmp/tartarus-firmware-signed.bin /tmp/app.bin
    else
        echo "Error: Signing key ($KEY_FILE) or espsecure.py not found! Cannot sign."
        exit 1
    fi

    echo "Packaging merged signed 4MB image..."
    cp /tmp/image.bin /tmp/image-signed.bin
    dd if=/tmp/bootloader.bin of=/tmp/image-signed.bin bs=1K seek=0 conv=notrunc 2>/dev/null
    dd if=/tmp/tartarus-firmware-signed.bin of=/tmp/image-signed.bin bs=1K seek=64 conv=notrunc 2>/dev/null

    UPDATE_IMAGE="tartarus-firmware-signed.bin"
    FULL_IMAGE="image-signed.bin"
    UPDATE_DESC="Tartarus Lock Firmware Update (Signed, preserves NVS)"
    FULL_DESC="Tartarus Lock Full Provisioning (Signed Bootloader + Partitions + App)"
else
    # In unsigned mode, use standard bootloader extracted from merged image
    cp /tmp/bootloader_4mb.bin /tmp/bootloader.bin
    UPDATE_IMAGE="app.bin"
    FULL_IMAGE="image.bin"
    UPDATE_DESC="Tartarus Lock Firmware Update (Unsigned, preserves NVS)"
    FULL_DESC="Tartarus Lock Full Provisioning (Bootloader + Partitions + App)"
fi

# Generate ESP Launchpad TOML manifest (Standard single-file format)
FIRMWARE_BASE_URL="${FIRMWARE_BASE_URL:-https://tartarus.subjugated.club/firmware2/}"
echo "Generating ESP Launchpad manifest (/tmp/manifest.toml)..."
cat << EOF > /tmp/manifest.toml
esp_toml_version = 1.0
firmware_images_url = "${FIRMWARE_BASE_URL}"
supported_apps = ["TartarusLock-Update", "TartarusLock-Full"]

[TartarusLock-Update]
chipsets = ["ESP32-S3"]
description = "${UPDATE_DESC}"
image.esp32-s3 = "${UPDATE_IMAGE}"
offset = "0x10000"

[TartarusLock-Full]
chipsets = ["ESP32-S3"]
description = "${FULL_DESC}"
image.esp32-s3 = "${FULL_IMAGE}"
offset = "0x0000"
EOF

# Also keep root manifest.toml in sync
cp /tmp/manifest.toml ./manifest.toml

echo "Firmware packaging complete:"
echo "  - Full merged image:   /tmp/${FULL_IMAGE} (flash at 0x0)"
echo "  - Bootloader:          /tmp/bootloader.bin (flash at 0x0)"
echo "  - Partition table:     /tmp/partitions.bin (flash at 0x8000)"
echo "  - Standalone app:      /tmp/${UPDATE_IMAGE} (flash at 0x10000)"
echo "  - Launchpad manifest:  /tmp/manifest.toml and ./manifest.toml"



